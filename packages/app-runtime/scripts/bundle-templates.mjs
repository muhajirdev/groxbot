#!/usr/bin/env node
/**
 * Assemble Groxbot app templates from Cloudflare OS gadget source.
 * Persistence stays gadget.load / gadget.save (see host-preamble.js).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const vendorRoot = path.join(root, "vendor", "cloudflare-os");
const outDir = path.join(root, "src", "generated");
const preamble = fs.readFileSync(path.join(root, "scripts", "host-preamble.js"), "utf8");
const boot = fs.readFileSync(path.join(root, "scripts", "host-boot.js"), "utf8");

function transformServer(src) {
  return src
    .replace(/^import\s+.*$/m, "")
    .replace(/^export\s+/gm, "")
    .trim();
}

function wrap(kind) {
  const dir = path.join(vendorRoot, kind);
  const server = transformServer(fs.readFileSync(path.join(dir, "server.js"), "utf8"));
  const client = fs.readFileSync(path.join(dir, "client.js"), "utf8");
  const header = [
    "/*",
    " * Derived from Cloudflare OS workspace gadgets",
    " * https://github.com/cloudflare/cloudflare-os",
    " * Copyright Cloudflare, Inc. Apache License 2.0.",
    " * Groxbot changes: iframe host implements Gadget RPC; parent load/save only.",
    " */",
  ].join("\n");
  const bundled = `${header}\n(async function () {\n${preamble}\n${server}\n${boot}\n${client}\n})();\n`;
  return bundled.replace(/<\/script/gi, "<\\/script");
}

fs.mkdirSync(outDir, { recursive: true });
for (const kind of ["docs", "slides", "sheets"]) {
  const js = wrap(kind);
  const ts =
    `/* Generated by scripts/bundle-templates.mjs — do not edit. */\n` +
    `export const ${kind}ClientJs = ${JSON.stringify(js)};\n`;
  fs.writeFileSync(path.join(outDir, `${kind}.client.ts`), ts);
  console.log(kind, "client.js", js.length, "bytes");
}
